import numpy as np
import math
import matplotlib.pyplot as plt
from typing import Callable, Tuple, List
from dataclasses import dataclass


@dataclass
class SolutionPoint:
    """Represents a single point in the solution."""
    t: float
    y: float
    
    def __str__(self) -> str:
        return f"t={self.t:.3f}, y={self.y:.6f}"


class EulerMethodSolver:
    """
    A beautiful implementation of Euler's method for solving ODEs.
    
    This class provides methods to solve differential equations numerically
    using Euler's method with customizable parameters and visualization options.
    """
    
    def __init__(self, differential_equation: Callable[[float, float], float]):
        """
        Initialize the solver with a differential equation.
        
        Args:
            differential_equation: Function f(t, y) representing dy/dt = f(t, y)
        """
        self.f = differential_equation
        self.solution_points: List[SolutionPoint] = []
    
    def solve(self, 
              t0: float, 
              y0: float, 
              h: float, 
              t_end: float) -> List[SolutionPoint]:
        """
        Solve the differential equation using Euler's method.
        
        Args:
            t0: Initial time value
            y0: Initial y value
            h: Step size
            t_end: Final time value
            
        Returns:
            List of SolutionPoint objects containing the numerical solution
            
        Raises:
            ValueError: If step size is non-positive or t_end <= t0
        """
        self._validate_parameters(t0, y0, h, t_end)
        
        # Calculate number of steps
        n_steps = int((t_end - t0) / h)
        
        # Initialize solution
        self.solution_points = [SolutionPoint(t0, y0)]
        
        # Current values
        t_current = t0
        y_current = y0
        
        # Euler's method iteration
        for step in range(n_steps):
            # Calculate next y value using Euler's formula: y_{n+1} = y_n + h * f(t_n, y_n)
            y_next = y_current + h * self.f(t_current, y_current)
            t_next = t_current + h
            
            # Store the solution point
            self.solution_points.append(SolutionPoint(t_next, y_next))
            
            # Update current values for next iteration
            t_current = t_next
            y_current = y_next
        
        return self.solution_points
    
    def _validate_parameters(self, t0: float, y0: float, h: float, t_end: float) -> None:
        """Validate input parameters."""
        if h <= 0:
            raise ValueError("Step size h must be positive")
        if t_end <= t0:
            raise ValueError("End time must be greater than start time")
    
    def print_solution_table(self) -> None:
        """Print a beautifully formatted table of the solution."""
        if not self.solution_points:
            print("No solution available. Please run solve() first.")
            return
        
        print("\n" + "="*50)
        print("🔢 EULER'S METHOD SOLUTION")
        print("="*50)
        print(f"{'Time (t)':<12} {'Solution (y)':<15} {'Step':<8}")
        print("-" * 50)
        
        for i, point in enumerate(self.solution_points):
            print(f"{point.t:<12.3f} {point.y:<15.6f} {i:<8}")
        
        print("="*50)
        print(f"✅ Solution completed with {len(self.solution_points)} points")
        print("="*50)
    
    def plot_solution(self, 
                     title: str = "Euler's Method Solution",
                     save_path: str = None,
                     show_points: bool = True) -> None:
        """
        Create a beautiful visualization of the solution.
        
        Args:
            title: Plot title
            save_path: Optional path to save the plot
            show_points: Whether to show individual solution points
        """
        if not self.solution_points:
            print("No solution available. Please run solve() first.")
            return
        
        # Extract t and y values
        t_vals = [point.t for point in self.solution_points]
        y_vals = [point.y for point in self.solution_points]
        
        # Create the plot with beautiful styling
        plt.figure(figsize=(10, 6))
        plt.style.use('seaborn-v0_8' if 'seaborn-v0_8' in plt.style.available else 'default')
        
        # Plot the solution curve
        plt.plot(t_vals, y_vals, 'b-', linewidth=2, label='Euler\'s Method Solution', alpha=0.8)
        
        # Optionally show individual points
        if show_points:
            plt.scatter(t_vals, y_vals, color='red', s=30, zorder=5, 
                       alpha=0.7, label='Solution Points')
        
        # Beautify the plot
        plt.xlabel('Time (t)', fontsize=12, fontweight='bold')
        plt.ylabel('Solution (y)', fontsize=12, fontweight='bold')
        plt.title(title, fontsize=14, fontweight='bold', pad=20)
        plt.grid(True, alpha=0.3)
        plt.legend(fontsize=10)
        
        # Add some styling
        plt.tight_layout()
        
        # Save if requested
        if save_path:
            plt.savefig(save_path, dpi=300, bbox_inches='tight')
            print(f"📊 Plot saved to: {save_path}")
        
        plt.show()
    
    def get_solution_arrays(self) -> Tuple[np.ndarray, np.ndarray]:
        """
        Get the solution as numpy arrays for further analysis.
        
        Returns:
            Tuple of (t_array, y_array)
        """
        if not self.solution_points:
            return np.array([]), np.array([])
        
        t_vals = np.array([point.t for point in self.solution_points])
        y_vals = np.array([point.y for point in self.solution_points])
        
        return t_vals, y_vals


def example_differential_equation(t: float, y: float) -> float:
    """
    Example differential equation: y' = t * e^(3t) - 2y
    
    This is the differential equation from the original code.
    """
    return t * math.exp(3 * t) - 2 * y


def main():
    """
    Main function demonstrating the beautiful Euler's method solver.
    """
    print("🚀 Beautiful Euler's Method Solver")
    print("=" * 40)
    
    # Create solver instance
    solver = EulerMethodSolver(example_differential_equation)
    
    # Define parameters
    t0, y0 = 0.0, 0.0  # Initial conditions
    h = 0.1            # Step size
    t_end = 1.0        # End time
    
    print(f"📋 Problem Setup:")
    print(f"   Differential Equation: y' = t * e^(3t) - 2y")
    print(f"   Initial Conditions: t₀ = {t0}, y₀ = {y0}")
    print(f"   Step Size: h = {h}")
    print(f"   Time Range: [{t0}, {t_end}]")
    
    try:
        # Solve the differential equation
        solution = solver.solve(t0, y0, h, t_end)
        
        # Display results
        solver.print_solution_table()
        
        # Create visualization
        solver.plot_solution(
            title="Solution of y' = t·e^(3t) - 2y using Euler's Method",
            show_points=True
        )
        
        # Get arrays for further analysis if needed
        t_array, y_array = solver.get_solution_arrays()
        
        print(f"\n📈 Final Result: y({t_end}) ≈ {y_array[-1]:.6f}")
        
    except ValueError as e:
        print(f"❌ Error: {e}")
    except Exception as e:
        print(f"❌ Unexpected error: {e}")


if __name__ == "__main__":
    main()